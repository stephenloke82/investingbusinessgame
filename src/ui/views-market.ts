// Market list and security (company / fund) detail views.
import type { GameState } from '../types';
import type { UiState } from './state';
import { html, raw, type Raw } from './html';
import { billions, compact, money, num, pct, signedPct, tone } from './format';
import { lineChart, sparkline } from './charts';
import { STOCKS, STOCK_DATA_AS_OF } from '../data/stocks';
import { ETFS } from '../data/etfs';
import { SECTORS, SECTOR_BY_ID } from '../data/sectors';
import { REGIMES } from '../data/marketModel';
import { eps, ETF_BY_TICKER, peRatio, priceOf, STOCK_BY_TICKER, spDrawdown } from '../engine/market';
import { ACCOUNT_LABELS, canHoldIn, contributionRoom, holdingCost, holdingShares } from '../engine/portfolio';
import type { AccountId } from '../types';

function change(hist: number[], months: number): number {
  if (hist.length < 2) return 0;
  const from = hist[Math.max(0, hist.length - 1 - months)];
  return hist[hist.length - 1] / from - 1;
}

interface Row {
  symbol: string;
  name: string;
  kind: string;
  sector: string;
  price: number;
  m1: number;
  y1: number;
  pe: number | null;
  yld: number;
  cap: number;
  hist: number[];
}

function rows(s: GameState): Row[] {
  const out: Row[] = [];
  for (const e of ETFS) {
    const st = s.market.etfs[e.ticker];
    out.push({ symbol: e.ticker, name: e.name, kind: 'fund', sector: e.kind, price: st.price, m1: change(st.history, 1), y1: change(st.history, 12), pe: null, yld: e.dividendYield / 100, cap: 1e9, hist: st.history });
  }
  for (const d of STOCKS) {
    const st = s.market.stocks[d.ticker];
    out.push({ symbol: d.ticker, name: d.name, kind: 'stock', sector: d.sector, price: st.price, m1: change(st.history, 1), y1: change(st.history, 12), pe: peRatio(st), yld: st.dividendYield, cap: st.price * st.sharesB, hist: st.history });
  }
  return out;
}

export function market(s: GameState, ui: UiState): Raw {
  let list = rows(s);
  const f = ui.marketFilter;
  if (f === 'funds') list = list.filter((r) => r.kind === 'fund');
  else if (f === 'stocks') list = list.filter((r) => r.kind === 'stock');
  else if (f !== 'all') list = list.filter((r) => r.sector === f);
  const q = ui.marketSearch.trim().toLowerCase();
  if (q) list = list.filter((r) => r.symbol.toLowerCase().includes(q) || r.name.toLowerCase().includes(q));
  const sorters: Record<string, (a: Row, b: Row) => number> = {
    cap: (a, b) => (a.kind === b.kind ? b.cap - a.cap : a.kind === 'fund' ? -1 : 1),
    name: (a, b) => a.name.localeCompare(b.name),
    m1: (a, b) => b.m1 - a.m1,
    y1: (a, b) => b.y1 - a.y1,
    pe: (a, b) => (a.pe ?? 1e9) - (b.pe ?? 1e9),
    yld: (a, b) => b.yld - a.yld,
  };
  list.sort(sorters[ui.marketSort] ?? sorters.cap);
  const sp = s.market.etfs.SPY.history;
  const regime = REGIMES[s.market.regime];
  return html`
  <section class="card">
    <div class="card-head"><h2>Market overview</h2><span class="pill regime-${s.market.regime}">${regime.label}</span></div>
    <div class="grid kpis compact">
      <div class="kpi"><div class="kpi-label">S&amp;P 500 (SPY)</div><div class="kpi-value">${money(sp[sp.length - 1], { cents: true })}</div><div class="kpi-sub"><span class="${tone(change(sp, 1))}">${signedPct(change(sp, 1))} 1M</span> · <span class="${tone(change(sp, 12))}">${signedPct(change(sp, 12))} 1Y</span></div></div>
      <div class="kpi"><div class="kpi-label">From all-time high</div><div class="kpi-value">${pct(-spDrawdown(s.market), 1)}</div><div class="kpi-sub">Drops are normal</div></div>
      <div class="kpi"><div class="kpi-label">Inflation</div><div class="kpi-value">${pct(s.market.inflation)}</div><div class="kpi-sub">per year</div></div>
      <div class="kpi"><div class="kpi-label">Cash rate</div><div class="kpi-value">${pct(s.market.cashRate)}</div><div class="kpi-sub">savings account</div></div>
    </div>
    <p class="muted small">Simulated market. Real company names with approximate starting data (${STOCK_DATA_AS_OF}). Prices, earnings and news are generated by the game and say nothing about the real companies.</p>
  </section>
  <section class="card">
    <div class="filters">
      <input type="search" placeholder="Search ticker or name" value="${ui.marketSearch}" data-bind-ui="marketSearch" aria-label="Search">
      <select data-bind-ui="marketFilter" aria-label="Filter">
        <option value="all" ${f === 'all' ? 'selected' : ''}>All (${ETFS.length + STOCKS.length})</option>
        <option value="funds" ${f === 'funds' ? 'selected' : ''}>Funds &amp; ETFs (${ETFS.length})</option>
        <option value="stocks" ${f === 'stocks' ? 'selected' : ''}>Stocks (${STOCKS.length})</option>
        ${SECTORS.map((x) => html`<option value="${x.id}" ${f === x.id ? 'selected' : ''}>${x.name}</option>`)}
      </select>
      <select data-bind-ui="marketSort" aria-label="Sort">
        ${[['cap', 'Biggest first'], ['name', 'Name'], ['m1', '1-month change'], ['y1', '1-year change'], ['pe', 'Lowest P/E'], ['yld', 'Highest yield']].map(([v, l]) => html`<option value="${v}" ${ui.marketSort === v ? 'selected' : ''}>${l}</option>`)}
      </select>
    </div>
    <div class="table-wrap"><table class="data market-table"><thead><tr><th>Symbol</th><th class="hide-sm">Name</th><th class="num">Price</th><th class="num">1M</th><th class="num">1Y</th><th class="num hide-sm">P/E</th><th class="num hide-sm">Yield</th><th class="hide-sm">Trend</th></tr></thead><tbody>
      ${list.map((r) => html`<tr class="clickable" data-action="open-security" data-symbol="${r.symbol}" tabindex="0">
        <td><b>${r.symbol}</b>${r.kind === 'fund' ? html` <span class="tag">fund</span>` : ''}<div class="muted small show-sm">${r.name}</div></td>
        <td class="hide-sm">${r.name}</td>
        <td class="num">${money(r.price, { cents: true })}</td>
        <td class="num ${tone(r.m1)}">${signedPct(r.m1)}</td>
        <td class="num ${tone(r.y1)}">${s.month >= 12 ? signedPct(r.y1) : '-'}</td>
        <td class="num hide-sm">${r.pe === null ? (r.kind === 'fund' ? '' : 'n/a') : num(r.pe, 1)}</td>
        <td class="num hide-sm">${r.yld > 0 ? pct(r.yld) : '-'}</td>
        <td class="hide-sm">${raw(sparkline(r.hist.slice(-24), r.y1 >= 0))}</td>
      </tr>`)}
    </tbody></table></div>
    ${list.length === 0 ? html`<p class="muted">No matches.</p>` : ''}
  </section>`;
}

function priceChart(s: GameState, ui: UiState, symbol: string, hist: number[]): Raw {
  const months = ui.chartRange === 'y1' ? 13 : ui.chartRange === 'y5' ? 61 : hist.length;
  const start = Math.max(0, hist.length - months);
  const slice = hist.slice(start);
  const labels = slice.map((_, i) => {
    const m = start + i;
    const names = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
    if (m === 0) return `Start ${s.startYear}`;
    return `${names[(m - 1) % 12]} ${s.startYear + Math.floor((m - 1) / 12)}`;
  });
  const sp = s.market.etfs.SPY.history.slice(start);
  const base = slice[0];
  const spBase = sp[0];
  const series =
    symbol === 'SPY'
      ? [{ name: symbol, slot: 1 as const, values: slice }]
      : [
          { name: symbol, slot: 1 as const, values: slice.map((v) => (v / base - 1) * 100) },
          { name: 'S&P 500', slot: 2 as const, dashed: true, values: sp.map((v) => (v / spBase - 1) * 100) },
        ];
  return html`
    <div class="seg">${(['y1', 'y5', 'max'] as const).map((r) => html`<button class="${ui.chartRange === r ? 'active' : ''}" data-action="chart-range" data-range="${r}">${r === 'y1' ? '1Y' : r === 'y5' ? '5Y' : 'All'}</button>`)}</div>
    ${raw(
      lineChart({
        title: `${symbol} price`,
        span: 'full',
        labels,
        zero: symbol !== 'SPY',
        fmt: symbol === 'SPY' ? (v) => money(v) : (v) => `${v >= 0 ? '+' : ''}${v.toFixed(0)}%`,
        series,
      }),
    )}
    ${symbol !== 'SPY' ? html`<p class="muted small">Price change since the start of the range, compared with the S&amp;P 500. Dividends not included.</p>` : ''}`;
}

function tradeBox(s: GameState, ui: UiState, symbol: string): Raw {
  const price = priceOf(s.market, symbol);
  const accts: AccountId[] = ['taxable', 'roth'];
  const acct = accts.includes(ui.tradeAccount) ? ui.tradeAccount : 'taxable';
  const owned = (['taxable', 'k401', 'roth'] as AccountId[])
    .map((a) => ({ a, h: s.accounts[a].holdings[symbol] }))
    .filter((x) => x.h && holdingShares(x.h) > 1e-9);
  return html`
  <section class="card trade">
    <div class="card-head"><h2>Trade ${symbol}</h2><span class="muted">${money(price, { cents: true })} per share</span></div>
    ${s.gameOver ? html`<p class="muted">The game is over.</p>` : html`
    <div class="inline">
      <select id="trade-account" data-bind-ui="tradeAccount" aria-label="Account">${accts.map((a) => html`<option value="${a}" ${acct === a ? 'selected' : ''} ${!canHoldIn(a, symbol) ? 'disabled' : ''}>${ACCOUNT_LABELS[a]}${a === 'roth' ? ` (room ${compact(contributionRoom(s, 'roth'))})` : ''}</option>`)}</select>
      <input type="number" id="trade-amount" min="1" step="50" placeholder="Amount in $" aria-label="Dollar amount">
    </div>
    <div class="inline quick">
      ${[0.1, 0.25, 0.5, 1].map((p) => html`<button class="btn small ghost" data-action="trade-fill" data-pct="${p}">${p === 1 ? 'All cash' : `${p * 100}% of cash`}</button>`)}
    </div>
    <div class="inline">
      <button class="btn primary" data-action="trade-buy" data-symbol="${symbol}">Buy</button>
      <button class="btn" data-action="trade-sell" data-symbol="${symbol}" ${owned.length ? '' : 'disabled'}>Sell</button>
    </div>
    <p class="muted small">Cash available: ${money(s.cash)}. Fractional shares allowed, no commissions. Sales in the brokerage account are taxed: ${'15%'} on gains held over a year, your income rate if less.</p>`}
    ${owned.length
      ? html`<h3>Your position</h3><ul class="rules">${owned.map(({ a, h }) => {
          const sh = holdingShares(h);
          const v = sh * price;
          const c = holdingCost(h);
          return html`<li>${ACCOUNT_LABELS[a]}: ${sh.toFixed(3)} shares = <b>${money(v)}</b> <span class="${tone(v - c)}">(${signedPct(c > 0 ? v / c - 1 : 0)})</span></li>`;
        })}</ul>`
      : ''}
  </section>`;
}

export function security(s: GameState, ui: UiState): Raw {
  const symbol = ui.symbol;
  const etf = ETF_BY_TICKER[symbol];
  const def = STOCK_BY_TICKER[symbol];
  if (!etf && !def) return html`<p>Unknown security.</p>`;
  if (etf) {
    const st = s.market.etfs[symbol];
    const exposure = Object.entries(etf.sectorWeights ?? {}).map(([k, w]) => `${SECTOR_BY_ID[k as keyof typeof SECTOR_BY_ID]?.name ?? k} ${Math.round((w ?? 0) * 100)}%`);
    return html`
    <button class="link back" data-action="back">← Back</button>
    <section class="card">
      <div class="sec-head">
        <div><h1>${etf.name}</h1><div class="muted">${symbol} · ${etf.kind === 'broad' ? 'Broad market index fund' : etf.kind} · ${num(etf.holdings)} holdings</div></div>
        <div class="sec-price"><div class="big">${money(st.price, { cents: true })}</div><div class="${tone(change(st.history, 12))}">${s.month >= 12 ? `${signedPct(change(st.history, 12))} past year` : `${signedPct(change(st.history, s.month))} since start`}</div></div>
      </div>
      <p>${etf.blurb}</p>
      ${priceChart(s, ui, symbol, st.history)}
    </section>
    <div class="grid two">
      <section class="card">
        <div class="card-head"><h2>Fund facts</h2></div>
        <dl class="facts">
          <dt>Expense ratio</dt><dd>${etf.expenseRatio.toFixed(2)}% / year <span class="muted small">(${money(etf.expenseRatio * 100)} per $10,000)</span></dd>
          <dt>Dividend yield</dt><dd>${etf.dividendYield ? `${etf.dividendYield.toFixed(2)}%` : 'None'}</dd>
          <dt>Holdings</dt><dd>${num(etf.holdings)}</dd>
          <dt>Market sensitivity</dt><dd>${etf.model === 'bond' ? 'Low (bonds)' : etf.model === 'gold' ? 'Independent (gold)' : `${etf.marketWeight.toFixed(2)}× the US market`}</dd>
          ${exposure.length ? html`<dt>Tilted toward</dt><dd>${exposure.join(', ')}</dd>` : ''}
          <dt>In 401(k) plan</dt><dd>${etf.in401k ? 'Yes' : 'No'}</dd>
        </dl>
      </section>
      ${tradeBox(s, ui, symbol)}
    </div>`;
  }
  const st = s.market.stocks[symbol];
  const sector = SECTOR_BY_ID[def.sector];
  const e = eps(st);
  const pe = peRatio(st);
  const cap = st.price * st.sharesB;
  const reports = [...st.earnings].reverse().slice(0, 8);
  const beats = st.earnings.filter((r) => r.eps >= r.epsEstimate).length;
  return html`
  <button class="link back" data-action="back">← Back</button>
  <section class="card">
    <div class="sec-head">
      <div><h1>${def.name}</h1><div class="muted">${symbol} · ${sector.name}</div></div>
      <div class="sec-price"><div class="big">${money(st.price, { cents: true })}</div><div class="${tone(change(st.history, 12))}">${s.month >= 12 ? `${signedPct(change(st.history, 12))} past year` : `${signedPct(change(st.history, s.month))} since start`}</div></div>
    </div>
    <p>${def.blurb}</p>
    ${priceChart(s, ui, symbol, st.history)}
  </section>
  <div class="grid two">
    <section class="card">
      <div class="card-head"><h2>Fundamentals</h2><span class="muted small">Simulated</span></div>
      <dl class="facts two-col">
        <dt>Market cap</dt><dd>${billions(cap)}</dd>
        <dt>Revenue (12 mo)</dt><dd>${billions(st.revenueB)}</dd>
        <dt>Revenue growth</dt><dd class="${tone(st.growth)}">${signedPct(st.growth)}</dd>
        <dt>Net margin</dt><dd class="${tone(st.margin)}">${pct(st.margin)}</dd>
        <dt>EPS (12 mo)</dt><dd>${money(e, { cents: true })}</dd>
        <dt>P/E ratio</dt><dd>${pe === null ? 'n/a (losing money)' : num(pe, 1)}</dd>
        <dt>Dividend yield</dt><dd>${st.dividendYield > 0 ? pct(st.dividendYield, 2) : 'None'}</dd>
        <dt>Debt / equity</dt><dd>${st.debtToEquity >= 9.9 ? 'Very high' : num(st.debtToEquity, 2)}</dd>
        <dt>Beta</dt><dd>${num(st.beta, 2)} <span class="muted small">(1 = moves with market)</span></dd>
        <dt>Company risk</dt><dd>${st.idioVol > 0.3 ? 'High' : st.idioVol > 0.18 ? 'Medium' : 'Low'} <span class="muted small">(${pct(st.idioVol, 0)} yearly swing)</span></dd>
      </dl>
      <p class="muted small">A P/E of ${pe === null ? '-' : num(pe, 0)} means investors pay ${pe === null ? '-' : money(pe)} for each $1 of yearly profit. High P/Es need fast growth to be worth it.</p>
    </section>
    ${tradeBox(s, ui, symbol)}
  </div>
  <section class="card">
    <div class="card-head"><h2>Quarterly earnings</h2><span class="muted">Beat estimates ${beats} of the last ${st.earnings.length} quarters</span></div>
    <div class="table-wrap"><table class="data"><thead><tr><th>Quarter</th><th class="num">Revenue</th><th class="num">EPS est.</th><th class="num">EPS actual</th><th class="num">Surprise</th><th class="num">Stock reaction</th></tr></thead><tbody>
      ${reports.map((r) => {
        const surprise = r.epsEstimate !== 0 ? (r.eps - r.epsEstimate) / Math.abs(r.epsEstimate) : 0;
        const beat = r.eps >= r.epsEstimate;
        return html`<tr><td>${r.label}</td><td class="num">${billions(r.revenueB)}</td><td class="num">${money(r.epsEstimate, { cents: true })}</td><td class="num">${money(r.eps, { cents: true })}</td>
          <td class="num ${beat ? 'up' : 'down'}">${beat ? '▲ Beat' : '▼ Miss'} ${signedPct(surprise)}</td><td class="num ${tone(r.reaction)}">${r.reaction >= 0 ? '+' : ''}${r.reaction.toFixed(1)}%</td></tr>`;
      })}
    </tbody></table></div>
    <p class="muted small">Companies usually beat estimates by a little, so small beats barely move the price. Big surprises in either direction cause big moves. Predicting them is very hard.</p>
  </section>`;
}
